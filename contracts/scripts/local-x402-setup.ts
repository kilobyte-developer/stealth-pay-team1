/**
 * LOCAL DEVELOPMENT ONLY — prepares a Hardhat node for browser-testing the
 * x402 + ERC-5564 flow without real Fuji funds.
 *
 *   1. Deploys ERC5564Announcer, StealthPaymentRouter, the test-only
 *      MockEIP3009Token ("USD Coin" / "2", 6 decimals — the FiatToken EIP-712
 *      domain) and a local StealthPayTestToken (stUSD) to the LOCAL node.
 *   2. Optionally funds LOCAL_SENDER_ADDRESS (a PUBLIC address). More
 *      addresses can be funded later with scripts/local-x402-fund.ts.
 *   3. Writes ../.env.development.local, which `next dev` loads (and
 *      `next build` ignores), pointing the app at the local chain.
 *
 * Refuses to run against anything but `--network localhost` on chainId 43113.
 * Never touches Fuji, the Fuji deployment record or deployed contracts.
 *
 * Usage:
 *   cd contracts
 *   npx hardhat node                                   # terminal 1
 *   npx hardhat run scripts/local-x402-setup.ts --network localhost
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ethers, network } from "hardhat";

const MARKER = "# Generated by contracts/scripts/local-x402-setup.ts";
const ENV_PATH = join(__dirname, "..", "..", ".env.development.local");
// Hardhat test-mnemonic account #2 — public, pre-funded by `hardhat node`,
// worthless anywhere else. Used as the announcement relayer.
const HARDHAT_ACCOUNT_2_KEY = "0x5de4111afa1a4b94908f83103eb1f1706367c2e68ca870fc3fb9a804cdab365a";

async function main() {
  const { chainId } = await ethers.provider.getNetwork();
  const clientVersion: string = await ethers.provider.send("web3_clientVersion", []);
  if (network.name !== "localhost" || chainId !== 43113n || !clientVersion.includes("HardhatNetwork")) {
    throw new Error(
      `Refusing to run: needs --network localhost on a Hardhat node with chainId 43113 (got ${network.name}, ${chainId}, ${clientVersion}).`,
    );
  }

  // Optional: fund an address right away. More can be funded later with
  // scripts/local-x402-fund.ts without redeploying.
  const senderRaw = process.env.LOCAL_SENDER_ADDRESS?.trim();
  if (senderRaw && !ethers.isAddress(senderRaw)) {
    throw new Error("LOCAL_SENDER_ADDRESS is not a valid address.");
  }
  const sender = senderRaw ? ethers.getAddress(senderRaw) : null;

  if (existsSync(ENV_PATH) && !readFileSync(ENV_PATH, "utf8").startsWith(MARKER)) {
    throw new Error(`${ENV_PATH} exists and was not written by this script; refusing to overwrite it.`);
  }

  const [deployer] = await ethers.getSigners();
  const startBlock = await ethers.provider.getBlockNumber();

  const announcer = await (await ethers.getContractFactory("ERC5564Announcer")).deploy();
  await announcer.waitForDeployment();
  const router = await (await ethers.getContractFactory("StealthPaymentRouter")).deploy(await announcer.getAddress());
  await router.waitForDeployment();
  const usdc = await (await ethers.getContractFactory("MockEIP3009Token")).deploy("USD Coin", "USDC", "2", 6);
  await usdc.waitForDeployment();
  // Local copy of the real stUSD contract, so the existing router ERC-20 path
  // can be regression-tested locally too.
  const stUsd = await (await ethers.getContractFactory("StealthPayTestToken")).deploy();
  await stUsd.waitForDeployment();

  if (sender) {
    await (await usdc.mint(sender, 1_000n * 10n ** 6n)).wait();
    await (await stUsd.faucet(1_000n * 10n ** 6n)).wait();
    await (await stUsd.transfer(sender, 1_000n * 10n ** 6n)).wait();
    await (await deployer.sendTransaction({ to: sender, value: ethers.parseEther("10") })).wait();
  }

  const addresses = {
    announcer: await announcer.getAddress(),
    router: await router.getAddress(),
    usdc: await usdc.getAddress(),
    stUsd: await stUsd.getAddress(),
  };

  const env = `${MARKER}
# LOCAL DEVELOPMENT ONLY. Loaded by \`next dev\`, ignored by \`next build\`.
# Points the app's "Fuji" network at a local Hardhat node (chainId 43113).
# Delete this file to go back to real Fuji.
NEXT_PUBLIC_FUJI_RPC_URL=http://127.0.0.1:8545

NEXT_PUBLIC_FUJI_ANNOUNCER_ADDRESS=${addresses.announcer}
NEXT_PUBLIC_FUJI_ROUTER_ADDRESS=${addresses.router}
NEXT_PUBLIC_FUJI_TEST_TOKEN_ADDRESS=${addresses.stUsd}
NEXT_PUBLIC_FUJI_SCAN_START_BLOCK=${startBlock}
NEXT_PUBLIC_FUJI_X402_ENABLED=true
NEXT_PUBLIC_FUJI_X402_USDC_ADDRESS=${addresses.usdc}
X402_FACILITATOR_URL=http://127.0.0.1:4022
X402_FUJI_RPC_URL=http://127.0.0.1:8545
# Hardhat public test account #2 — worthless outside a local node.
STEALTHPAY_RELAYER_PRIVATE_KEY=${HARDHAT_ACCOUNT_2_KEY}
STEALTHPAY_X402_STORE_PATH=.stealthpay/local-x402-payments.json
`;
  writeFileSync(ENV_PATH, env, "utf8");

  console.log("Local x402 environment ready (chainId 43113 on 127.0.0.1:8545)");
  console.log(`  ERC5564Announcer      ${addresses.announcer}`);
  console.log(`  StealthPaymentRouter  ${addresses.router}`);
  console.log(`  USDC (MockEIP3009)    ${addresses.usdc}`);
  console.log(`  stUSD (local copy)    ${addresses.stUsd}`);
  console.log(sender ? `  Funded                ${sender}: 1000 USDC + 1000 stUSD + 10 AVAX` : "  Funded                (none — use scripts/local-x402-fund.ts)");
  console.log(`  Scan start block      ${startBlock}`);
  console.log(`  Wrote                 ${ENV_PATH}`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exitCode = 1;
});
